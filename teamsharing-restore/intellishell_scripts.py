#!/usr/bin/env python3
"""
Generate self-contained Studio 3T IntelliShell (mongosh) scripts that insert an export produced by
teamsharing_restore.py into production - insert only, idempotent, verified.

Why scripts instead of the Studio 3T import dialog: the dialog's insert/upsert mode is easy to get
wrong, and IntelliShell runs a script statement by statement and KEEPS GOING after a failed
statement. The generated scripts are built for exactly that:

  * every binary value is its own one-line statement (`var b03_content = "<base64>";`),
    every document its own statement, every insert its own statement
  * before each insert: base64 length + FNV-1a checksum of every binary field are compared with
    numbers embedded in the script, then BinData.length() with the expected byte count - a value
    the shell damaged is refused, never written
  * after each insert: the stored document is read back and every binary field's $binarySize
    checked; on mismatch the just-written document is deleted again
  * a global ABORT flag: once a guard fails, every later statement prints "skip (aborted)" and
    writes nothing, even though IntelliShell keeps executing statements
  * documents whose _id already exists are skipped (never modified), so the scripts can be
    re-run and also cover partial deletions
  * a guard refuses to run unless the connection's replica set name is the production one

Generated files (in <export>/scripts/):
  01-preflight.js   read-only: guards, counts, how many export _ids already exist per collection
  02-..06-*.js      one insert script per collection, in production insert order
  07-postcheck.js   read-only: every export _id present, binary sizes verified
  08-rollback.js    deletes ONLY the _ids you paste in from the insert scripts' output; CONFIRM flag

Usage:
    python intellishell_scripts.py <export-dir> [--prod-set NAME] [--prefix "[restored] "] [--out DIR]
"""

import argparse
import base64
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

DEFAULT_PROD_SET = "atlas-blssko-shard-0"   # replica set name of the Team Sharing production cluster
EXPECTED_FILES = [
    "1-ENCRYPTION_PROD.__keyVault.json",
    "2-TEAM_SHARING_ENCRYPTED_PROD.folder.json",
    "3-TEAM_SHARING_ENCRYPTED_PROD.permission.json",
    "4-TEAM_SHARING_ENCRYPTED_PROD.resource.json",
    "5-TEAM_SHARING_ENCRYPTED_PROD.resourceContent.json",
]


def fnv1a(s: str) -> int:
    h = 0x811C9DC5
    for ch in s.encode("utf-8"):
        h ^= ch
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def _js_value(v, binaries: Dict[str, str], path: str):
    """Canonical Extended JSON -> shell syntax. Top-level binaries are replaced by a variable name
    (collected in `binaries`); nested binaries are not supported."""
    if isinstance(v, dict):
        if "$oid" in v:
            return f'ObjectId("{v["$oid"]}")'
        if "$binary" in v:
            if "." in path:
                raise ValueError(f"nested binary field {path!r} is not supported")
            var = binaries[path]
            return f'BinData({int(v["$binary"]["subType"], 16)}, {var})'
        if "$numberInt" in v:
            return f'NumberInt({v["$numberInt"]})'
        if "$numberLong" in v:
            return f'NumberLong("{v["$numberLong"]}")'
        if "$numberDouble" in v:
            return v["$numberDouble"]
        if "$date" in v:
            d = v["$date"]
            return f'ISODate("{d}")' if isinstance(d, str) else f'new Date({d["$numberLong"]})'
        return "{" + ", ".join(f"{json.dumps(k)}: {_js_value(x, binaries, f'{path}.{k}' if path else k)}"
                               for k, x in v.items()) + "}"
    if isinstance(v, list):
        return "[" + ", ".join(_js_value(x, binaries, f"{path}[]") for x in v) + "]"
    return json.dumps(v)


def _id_literal(doc: dict) -> str:
    """Shell literal for a document's _id (ObjectId, UUID/binary or plain value)."""
    v = doc["_id"]
    if isinstance(v, dict) and "$binary" in v:
        return f'BinData({int(v["$binary"]["subType"], 16)}, "{v["$binary"]["base64"]}")'
    return _js_value(v, {}, "_id")


def _label(doc: dict) -> str:
    for k in ("name", "email", "right"):
        if isinstance(doc.get(k), str):
            return doc[k].replace('"', "'")[:60]
    if "keyAltNames" in doc and doc["keyAltNames"]:
        return str(doc["keyAltNames"][0])[:60]
    return ""


def _header(title: str, prod_set: str, db_name: str) -> str:
    return f'''// =====================================================================================================
// {title}
// Generated by teamsharing-restore/intellishell_scripts.py for Studio 3T IntelliShell (mongosh).
// INSERT ONLY: existing documents are never modified or deleted. Safe to run again.
// Run the whole file (F5) in an IntelliShell on the PRODUCTION connection, database {db_name}.
// =====================================================================================================
var ABORT = false;
function say(m) {{ print(m); }}
function fail(m) {{ ABORT = true; say("!! " + m + "  -> ABORT: nothing more will be written."); }}
function fnv1a(s) {{ var h = 0x811c9dc5; for (var i = 0; i < s.length; i++) {{ h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }} return h >>> 0; }}
var PROD_SET = {json.dumps(prod_set)};
var DB_NAME  = {json.dumps(db_name)};
say("=== {title} ===");
var hello = db.getSiblingDB("admin").runCommand({{ hello: 1 }});
say("shell: " + (typeof version === "function" ? version() : "?") + " | replica set: " + (hello.setName || "standalone") + " | primary: " + hello.isWritablePrimary + " | database: " + db.getName());
if (PROD_SET && hello.setName !== PROD_SET) fail("connected to '" + (hello.setName || "standalone") + "', expected production '" + PROD_SET + "'");
if (fnv1a("abc") !== 440920331) fail("checksum function does not work in this shell");
function idText(v) {{ return (typeof EJSON !== "undefined") ? EJSON.stringify(v) : String(v); }}
'''


PUT_FN = '''var inserted = 0, skipped = 0, refused = 0, repaired = 0, insertedIds = [];
// doc: the document; bins: [[field, base64, expectedBase64Length, expectedFnv, expectedBytes], ...]
function put(doc, bins, label) {
  var tag = "[" + label + "] " + idText(doc._id);
  if (ABORT) { say("   skip (aborted) " + tag); return; }
  for (var i = 0; i < bins.length; i++) {
    var f = bins[i][0], b64 = bins[i][1];
    if (b64.length !== bins[i][2]) { refused++; fail(tag + " " + f + ": base64 length " + b64.length + " != " + bins[i][2] + " (shell damaged the data)"); return; }
    if (fnv1a(b64) !== bins[i][3]) { refused++; fail(tag + " " + f + ": base64 checksum mismatch (shell damaged the data)"); return; }
    if (doc[f].length() !== bins[i][4]) { refused++; fail(tag + " " + f + ": BinData has " + doc[f].length() + " bytes, expected " + bins[i][4]); return; }
  }
  if (!EXTRA_CHECK(doc, tag)) { refused++; return; }
  if (COLL.countDocuments({ _id: doc._id }) !== 0) { skipped++; say("   skip  already present " + tag); return; }
  var r = COLL.insertOne(doc);
  if (!r.acknowledged) { refused++; fail(tag + " insert not acknowledged"); return; }
  if (bins.length) {
    var proj = {}; for (var j = 0; j < bins.length; j++) proj[bins[j][0]] = { $binarySize: "$" + bins[j][0] };
    var back = COLL.aggregate([{ $match: { _id: doc._id } }, { $project: proj }]).toArray()[0];
    for (var k = 0; k < bins.length; k++) {
      if (!back || back[bins[k][0]] !== bins[k][4]) {
        COLL.deleteOne({ _id: doc._id }); repaired++; refused++;
        fail(tag + " stored " + (back ? back[bins[k][0]] : "nothing") + " bytes in " + bins[k][0] + " instead of " + bins[k][4] + " - removed it again"); return;
      }
    }
  } else if (COLL.countDocuments({ _id: doc._id }) !== 1) { refused++; fail(tag + " not found after insert"); return; }
  inserted++; insertedIds.push(doc._id); say("   ok    inserted " + tag + (bins.length ? " (" + bins.map(function (b) { return b[0] + " " + b[4] + " B"; }).join(", ") + " verified)" : ""));
}
'''


def _emit_insert(docs: List[dict], db_name: str, coll: str, step: int, prod_set: str,
                 extra_check: str, prefix: Optional[str]) -> Tuple[str, List[str]]:
    title = f"{step:02d} - insert {len(docs)} {db_name}.{coll} documents" + (f" (names prefixed {prefix!r})" if prefix and coll == "resource" else "")
    out = [_header(title, prod_set, db_name),
           f'var COLL = db.getSiblingDB({json.dumps(db_name)}).getCollection({json.dumps(coll)});',
           f'function EXTRA_CHECK(doc, tag) {{{extra_check}\n  return true;\n}}',
           PUT_FN]
    ids = []
    for i, d in enumerate(docs, 1):
        d = dict(d)
        if prefix and coll == "resource" and isinstance(d.get("name"), str) and not d["name"].startswith(prefix):
            d["name"] = prefix + d["name"]
        binaries = {k: f"b{i:02d}_{k.strip('_')}" for k, v in d.items() if isinstance(v, dict) and "$binary" in v}
        bins = []
        for k, var in binaries.items():
            b64 = d[k]["$binary"]["base64"]
            out.append(f'var {var} = {json.dumps(b64)};')
            bins.append(f'["{k}", {var}, {len(b64)}, {fnv1a(b64)}, {len(base64.b64decode(b64))}]')
        out.append(f'var d{i:02d} = {_js_value(d, binaries, "")};')
        out.append(f'put(d{i:02d}, [{", ".join(bins)}], {json.dumps(_label(d))});')
        ids.append(_id_literal(d))
    out.append(f'''var ALL_IDS = [{", ".join(ids)}];
var present = COLL.countDocuments({{ _id: {{ $in: ALL_IDS }} }});
say("---- summary {step:02d}: inserted " + inserted + ", skipped(already present) " + skipped + ", refused " + refused + ", removed-after-bad-write " + repaired);
say("     {db_name}.{coll}: " + present + " of {len(docs)} export documents present");
say("     inserted _ids (paste into 08-rollback.js if you ever need to undo): " + idText(insertedIds));
if (ABORT) say("RESULT {step:02d}: ABORTED - nothing wrong was written. Fix the cause and run this script again; it continues where it stopped.");
else if (present === {len(docs)}) say("RESULT {step:02d}: OK - all {len(docs)} documents present. Continue with the next script.");
else say("RESULT {step:02d}: INCOMPLETE - " + present + " of {len(docs)} present. Run again or investigate.");
''')
    return "\n".join(out) + "\n", ids


def generate(export_dir: Path, out_dir: Optional[Path] = None, prod_set: str = DEFAULT_PROD_SET,
             prefix: Optional[str] = None) -> List[Path]:
    out_dir = out_dir or export_dir / "scripts"
    out_dir.mkdir(parents=True, exist_ok=True)
    collections = []   # (db, coll, docs)
    for name in EXPECTED_FILES:
        path = export_dir / name
        if not path.is_file():
            raise FileNotFoundError(f"missing export file {path}")
        db_name, coll = name.split("-", 1)[1][:-5].split(".", 1)
        collections.append((db_name, coll, json.load(open(path, encoding="utf-8"))))

    written = []
    id_lists = {}
    # ---- 01 preflight ------------------------------------------------------------------------------
    main_db = collections[1][0]
    pre = [_header("01 - pre-flight (read-only)", prod_set, main_db)]
    for db_name, coll, docs in collections:
        ids = [_id_literal(d) for d in docs]
        id_lists[(db_name, coll)] = ids
        pre.append(f'''var ids_{coll.strip("_")} = [{", ".join(ids)}];
say("  {db_name}.{coll}: export has {len(docs)} document(s); already in production: " + db.getSiblingDB({json.dumps(db_name)}).getCollection({json.dumps(coll)}).countDocuments({{ _id: {{ $in: ids_{coll.strip("_")} }} }}) + " (these will be skipped, not modified)");''')
    pre.append('say(ABORT ? "RESULT 01: STOP - fix the connection first." : "RESULT 01: OK - continue with 02.");')
    p = out_dir / "01-preflight.js"
    p.write_text("\n".join(pre) + "\n", encoding="utf-8"); written.append(p)

    # ---- 02..06 inserts, production order ---------------------------------------------------------
    extra = {
        "resource": '''
  if (db.getSiblingDB("TEAM_SHARING_ENCRYPTED_PROD").getCollection("resourceContent").countDocuments({ _id: doc.contentId }) !== 1) { fail(tag + " its resourceContent " + doc.contentId + " is not present - run the resourceContent script first"); return false; }
  if (COLL.countDocuments({ contentId: doc.contentId, _id: { $ne: doc._id } }) !== 0) { fail(tag + " contentId " + doc.contentId + " is already referenced by another resource"); return false; }''',
    }
    # resourceContent before resource: a content document without its resource is invisible, the reverse is not
    order = [c for c in collections if c[1] != "resource"] + [c for c in collections if c[1] == "resource"]
    for step, (db_name, coll, docs) in enumerate(order, 2):
        text, _ = _emit_insert(docs, db_name, coll, step, prod_set, extra.get(coll, ""), prefix)
        p = out_dir / f"{step:02d}-insert-{coll.strip('_')}.js"
        p.write_text(text, encoding="utf-8"); written.append(p)

    # ---- 07 postcheck ---------------------------------------------------------------------------
    post = [_header("07 - post-check (read-only)", prod_set, main_db), "var problems = 0;"]
    for db_name, coll, docs in collections:
        ids = id_lists[(db_name, coll)]
        post.append(f'''var ids_{coll.strip("_")} = [{", ".join(ids)}];
var n_{coll.strip("_")} = db.getSiblingDB({json.dumps(db_name)}).getCollection({json.dumps(coll)}).countDocuments({{ _id: {{ $in: ids_{coll.strip("_")} }} }});
say("  " + (n_{coll.strip("_")} === {len(docs)} ? "ok   " : "DIFF ") + "{db_name}.{coll}: " + n_{coll.strip("_")} + " of {len(docs)} present"); if (n_{coll.strip("_")} !== {len(docs)}) problems++;''')
    post.append('''var orphans = db.getSiblingDB("TEAM_SHARING_ENCRYPTED_PROD").getCollection("resource").find({ _id: { $in: ids_resource } }).toArray()
  .filter(function (r) { return db.getSiblingDB("TEAM_SHARING_ENCRYPTED_PROD").getCollection("resourceContent").countDocuments({ _id: r.contentId }) === 0; }).length;
say("  " + (orphans === 0 ? "ok   " : "DIFF ") + "resources without content: " + orphans); if (orphans) problems++;
say(problems ? "RESULT 07: DIFFERS (" + problems + ") - investigate before anything else." : "RESULT 07: OK - restore complete and verified.");''')
    p = out_dir / "07-postcheck.js"
    p.write_text("\n".join(post) + "\n", encoding="utf-8"); written.append(p)

    # ---- 08 rollback ----------------------------------------------------------------------------
    rb = [_header("08 - rollback: deletes ONLY the _ids pasted below (from the insert scripts' output)", prod_set, main_db),
          "var CONFIRM = false;   // <-- set to true to actually delete",
          'if (!CONFIRM) fail("CONFIRM is false");',
          "// Paste the 'inserted _ids' arrays printed by the insert scripts (Extended JSON, e.g. [{\"$oid\":\"...\"}]).",
          "// Only _ids that are part of the export are accepted; anything else makes the script refuse."]
    for db_name, coll, docs in reversed(order):
        ids = id_lists[(db_name, coll)]
        v = coll.strip("_")
        rb.append(f'''var del_{v} = EJSON.deserialize([]);   // <-- paste the array from the {coll} insert script inside the ( )
var allowed_{v} = [{", ".join(ids)}].map(idText);
var bad_{v} = del_{v}.filter(function (x) {{ return allowed_{v}.indexOf(idText(x)) < 0; }});
if (bad_{v}.length) fail("{coll}: " + bad_{v}.length + " id(s) are not part of the export - refusing");
if (CONFIRM && !ABORT && del_{v}.length) {{ var r_{v} = db.getSiblingDB({json.dumps(db_name)}).getCollection({json.dumps(coll)}).deleteMany({{ _id: {{ $in: del_{v} }} }}); say("  deleted from {db_name}.{coll}: " + r_{v}.deletedCount); }}''')
    rb.append('say(ABORT ? "RESULT 08: nothing deleted." : "RESULT 08: done.");')
    p = out_dir / "08-rollback.js"
    p.write_text("\n".join(rb) + "\n", encoding="utf-8"); written.append(p)
    return written


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("export_dir", type=Path, help="folder written by the restore tool's export step")
    ap.add_argument("--out", type=Path, default=None, help="output folder (default: <export_dir>/scripts)")
    ap.add_argument("--prod-set", default=DEFAULT_PROD_SET, help="replica set name the scripts insist on (empty = no check)")
    ap.add_argument("--prefix", default=None, help='prefix added to every resource name, e.g. "[restored] "')
    a = ap.parse_args()
    for p in generate(a.export_dir, a.out, a.prod_set, a.prefix):
        print(f"{p}  ({p.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
